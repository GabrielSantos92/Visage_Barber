-- =====================================================================
-- Esquema das tabelas do chat (conversas e mensagens) e inventario do banco
-- SOMENTE LEITURA. NAO execute sem autorizacao.
--
-- Por que existe: conversas e mensagens foram criadas fora das migrations, e
-- uma instalacao nova para na migration 20261001000011 (ALTER TABLE
-- public.mensagens). O repositorio nao tem a definicao real dessas tabelas;
-- ela vai virar o script de preparacao do projeto de TESTE
-- (supabase/teste/00_dependencias_chat.sql, a criar com o resultado da
-- consulta 1).
--
-- O que estas consultas leem: SO o catalogo do PostgreSQL (pg_catalog:
-- pg_class, pg_attribute, pg_constraint, pg_index, pg_policy, pg_trigger,
-- pg_proc, pg_type, pg_publication_tables, pg_extension). Nenhuma linha de
-- tabela do sistema e lida: nem conversas, nem mensagens, nem perfis.
-- Nenhuma contagem de linhas. Cada consulta e um unico SELECT: nao altera
-- tabelas, permissoes, policies, funcoes nem dados.
--
-- Como usar (depois de autorizado):
--   Supabase Dashboard > SQL Editor > cole SO a consulta 1 > Run. O resultado
--   e uma unica celula de texto (o SQL que recria as duas tabelas). Copie-a
--   inteira. Depois, do mesmo jeito, a consulta 2 (uma celula JSON).
--   Rodar no psql com a conexao do projeto tambem serve:
--     BEGIN READ ONLY; <consulta>; ROLLBACK;
--   (BEGIN READ ONLY faz o banco recusar qualquer escrita.)
-- =====================================================================


-- ---------------------------------------------------------------------
-- Consulta 1: definicao completa de public.conversas e public.mensagens
-- (tipos usados, colunas, padroes, NOT NULL, chaves, indices, RLS,
-- policies, permissoes, gatilhos e publicacao do Realtime)
-- ---------------------------------------------------------------------
WITH tabelas AS (
  SELECT c.oid, c.relname, c.relrowsecurity, c.relforcerowsecurity, c.relreplident,
         CASE c.relname WHEN 'conversas' THEN 1 ELSE 2 END AS ordem
    FROM pg_catalog.pg_class c
    JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
   WHERE n.nspname = 'public' AND c.relname IN ('conversas', 'mensagens') AND c.relkind IN ('r', 'p')
),
tipos AS (
  -- Enums e dominios do esquema public usados pelas colunas
  SELECT DISTINCT ty.oid, ty.typname, ty.typtype
    FROM tabelas t
    JOIN pg_catalog.pg_attribute a ON a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped
    JOIN pg_catalog.pg_type ty ON ty.oid = a.atttypid
    JOIN pg_catalog.pg_namespace tn ON tn.oid = ty.typnamespace
   WHERE tn.nspname = 'public' AND ty.typtype IN ('e', 'd')
),
partes AS (
  -- 1. tipos
  SELECT 1 AS etapa, 0 AS ordem, ty.typname AS chave,
         CASE ty.typtype
           WHEN 'e' THEN format('CREATE TYPE public.%I AS ENUM (%s);', ty.typname,
             (SELECT string_agg(quote_literal(e.enumlabel), ', ' ORDER BY e.enumsortorder)
                FROM pg_catalog.pg_enum e WHERE e.enumtypid = ty.oid))
           ELSE format('CREATE DOMAIN public.%I AS %s;  -- conferir restricoes do dominio', ty.typname,
             (SELECT format_type(d.typbasetype, d.typtypmod) FROM pg_catalog.pg_type d WHERE d.oid = ty.oid))
         END AS sql
    FROM tipos ty
  UNION ALL
  -- 2. tabelas com colunas, padroes e NOT NULL
  SELECT 2, t.ordem, t.relname,
         format(E'CREATE TABLE public.%I (\n%s\n);', t.relname,
           (SELECT string_agg(format('  %I %s%s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
                     CASE a.attidentity WHEN 'a' THEN ' GENERATED ALWAYS AS IDENTITY'
                                        WHEN 'd' THEN ' GENERATED BY DEFAULT AS IDENTITY' ELSE '' END,
                     CASE WHEN a.attgenerated = 's' THEN ' GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                          WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid)
                          ELSE '' END,
                     CASE WHEN a.attnotnull THEN ' NOT NULL' ELSE '' END), E',\n' ORDER BY a.attnum)
              FROM pg_catalog.pg_attribute a
              LEFT JOIN pg_catalog.pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
             WHERE a.attrelid = t.oid AND a.attnum > 0 AND NOT a.attisdropped))
    FROM tabelas t
  UNION ALL
  -- 3. chaves primarias, unicas, checks e exclusoes (antes das estrangeiras)
  SELECT 3, t.ordem, k.conname,
         format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, k.conname, pg_get_constraintdef(k.oid))
    FROM tabelas t JOIN pg_catalog.pg_constraint k ON k.conrelid = t.oid
   WHERE k.contype IN ('p', 'u', 'c', 'x')
  UNION ALL
  -- 4. chaves estrangeiras
  SELECT 4, t.ordem, k.conname,
         format('ALTER TABLE public.%I ADD CONSTRAINT %I %s;', t.relname, k.conname, pg_get_constraintdef(k.oid))
    FROM tabelas t JOIN pg_catalog.pg_constraint k ON k.conrelid = t.oid
   WHERE k.contype = 'f'
  UNION ALL
  -- 5. indices que nao vem de uma restricao
  SELECT 5, t.ordem, ic.relname, pg_get_indexdef(i.indexrelid) || ';'
    FROM tabelas t
    JOIN pg_catalog.pg_index i ON i.indrelid = t.oid
    JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
   WHERE NOT EXISTS (SELECT 1 FROM pg_catalog.pg_constraint k WHERE k.conindid = i.indexrelid AND k.conrelid = t.oid)
  UNION ALL
  -- 6. RLS
  SELECT 6, t.ordem, t.relname,
         format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY;', t.relname)
           || CASE WHEN t.relforcerowsecurity THEN format(' ALTER TABLE public.%I FORCE ROW LEVEL SECURITY;', t.relname) ELSE '' END
    FROM tabelas t WHERE t.relrowsecurity
  UNION ALL
  -- 7. policies
  SELECT 7, t.ordem, p.polname,
         format('CREATE POLICY %I ON public.%I AS %s FOR %s TO %s%s%s;', p.polname, t.relname,
           CASE WHEN p.polpermissive THEN 'PERMISSIVE' ELSE 'RESTRICTIVE' END,
           CASE p.polcmd WHEN 'r' THEN 'SELECT' WHEN 'a' THEN 'INSERT' WHEN 'w' THEN 'UPDATE' WHEN 'd' THEN 'DELETE' ELSE 'ALL' END,
           (SELECT string_agg(CASE WHEN r.oid = 0 THEN 'public' ELSE quote_ident(rl.rolname) END, ', ' ORDER BY 1)
              FROM unnest(p.polroles) AS r(oid) LEFT JOIN pg_catalog.pg_roles rl ON rl.oid = r.oid),
           CASE WHEN p.polqual IS NOT NULL THEN ' USING (' || pg_get_expr(p.polqual, p.polrelid) || ')' ELSE '' END,
           CASE WHEN p.polwithcheck IS NOT NULL THEN ' WITH CHECK (' || pg_get_expr(p.polwithcheck, p.polrelid) || ')' ELSE '' END)
    FROM tabelas t JOIN pg_catalog.pg_policy p ON p.polrelid = t.oid
  UNION ALL
  -- 8. permissoes da tabela (papeis do Supabase e outros)
  SELECT 8, t.ordem, g.grantee,
         format('GRANT %s ON public.%I TO %s;', g.privilegios, t.relname, g.grantee)
    FROM tabelas t
    JOIN LATERAL (
      SELECT CASE WHEN x.grantee = 0 THEN 'PUBLIC' ELSE quote_ident(rl.rolname) END AS grantee,
             string_agg(x.privilege_type, ', ' ORDER BY x.privilege_type) AS privilegios
        FROM pg_catalog.pg_class c, aclexplode(c.relacl) x
        LEFT JOIN pg_catalog.pg_roles rl ON rl.oid = x.grantee
       WHERE c.oid = t.oid
       GROUP BY 1
    ) g ON true
  UNION ALL
  -- 9. gatilhos (comentados: alguns sao criados por migrations, ex.:
  --    notificar_mensagem da 22; a revisao decide o que entra)
  SELECT 9, t.ordem, tg.tgname,
         '-- GATILHO: ' || pg_get_triggerdef(tg.oid) || ';  -- funcao: ' || tg.tgfoid::regprocedure::text
    FROM tabelas t JOIN pg_catalog.pg_trigger tg ON tg.tgrelid = t.oid
   WHERE NOT tg.tgisinternal
  UNION ALL
  -- 10. Realtime e identidade de replica
  SELECT 10, 0, pt.pubname || '.' || pt.tablename,
         format('-- PUBLICACAO: ALTER PUBLICATION %I ADD TABLE public.%I;', pt.pubname, pt.tablename)
    FROM pg_catalog.pg_publication_tables pt
   WHERE pt.schemaname = 'public' AND pt.tablename IN ('conversas', 'mensagens')
  UNION ALL
  SELECT 10, t.ordem, t.relname,
         format('-- REPLICA IDENTITY de public.%I: %s', t.relname,
           CASE t.relreplident WHEN 'd' THEN 'DEFAULT' WHEN 'f' THEN 'FULL' WHEN 'n' THEN 'NOTHING' ELSE 'INDEX' END)
    FROM tabelas t
)
SELECT concat_ws(E'\n',
         '-- Gerado em ' || to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI') || ' UTC, PostgreSQL '
           || current_setting('server_version'),
         '-- Tabelas encontradas: ' || coalesce((SELECT string_agg(relname, ', ' ORDER BY ordem) FROM tabelas), 'NENHUMA'),
         string_agg(sql, E'\n' ORDER BY etapa, ordem, chave)) AS definicao_chat
  FROM partes;


-- ---------------------------------------------------------------------
-- Consulta 2: inventario do esquema (para comparar com uma instalacao nova
-- e achar o que mais foi criado fora das migrations). So nomes, tipos e
-- definicoes; nenhuma linha de tabela.
-- ---------------------------------------------------------------------
SELECT jsonb_pretty(jsonb_build_object(
  'postgres', current_setting('server_version'),
  'extensoes', (SELECT jsonb_agg(e.extname || ' ' || e.extversion ORDER BY e.extname) FROM pg_catalog.pg_extension e),
  'tabelas', (
    SELECT jsonb_object_agg(c.relname, jsonb_build_object(
             'tipo', c.relkind::text,
             'rls', c.relrowsecurity,
             'colunas', (SELECT jsonb_agg(a.attname || ' ' || format_type(a.atttypid, a.atttypmod)
                                          || CASE WHEN a.attnotnull THEN ' not null' ELSE '' END ORDER BY a.attnum)
                           FROM pg_catalog.pg_attribute a
                          WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped),
             'restricoes', (SELECT jsonb_agg(k.conname || ' ' || k.contype::text ORDER BY k.conname)
                              FROM pg_catalog.pg_constraint k WHERE k.conrelid = c.oid AND k.contype IN ('p', 'u', 'f', 'c', 'x')),
             'indices', (SELECT jsonb_agg(ic.relname ORDER BY ic.relname)
                           FROM pg_catalog.pg_index i JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
                          WHERE i.indrelid = c.oid)))
      FROM pg_catalog.pg_class c JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
     WHERE n.nspname = 'public' AND c.relkind IN ('r', 'p', 'v', 'm')),
  'policies', (SELECT jsonb_agg(p.schemaname || '.' || p.tablename || ': ' || p.policyname || ' (' || p.cmd || ')'
                                ORDER BY p.schemaname, p.tablename, p.policyname)
                 FROM pg_catalog.pg_policies p WHERE p.schemaname IN ('public', 'storage')),
  'gatilhos', (SELECT jsonb_agg(c.relname || ': ' || tg.tgname || ' -> ' || tg.tgfoid::regprocedure::text
                                ORDER BY c.relname, tg.tgname)
                 FROM pg_catalog.pg_trigger tg
                 JOIN pg_catalog.pg_class c ON c.oid = tg.tgrelid
                 JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
                WHERE NOT tg.tgisinternal AND n.nspname IN ('public', 'auth', 'storage')),
  'funcoes', (SELECT jsonb_agg(p.oid::regprocedure::text ORDER BY 1)
                FROM pg_catalog.pg_proc p JOIN pg_catalog.pg_namespace n ON n.oid = p.pronamespace
               WHERE n.nspname = 'public'),
  'tipos', (SELECT jsonb_agg(t.typname || ' ' || t.typtype::text ORDER BY t.typname)
              FROM pg_catalog.pg_type t JOIN pg_catalog.pg_namespace n ON n.oid = t.typnamespace
             WHERE n.nspname = 'public' AND t.typtype IN ('e', 'd', 'c')
               AND NOT EXISTS (SELECT 1 FROM pg_catalog.pg_class c WHERE c.reltype = t.oid)),
  'publicacoes', (SELECT jsonb_agg(pt.pubname || ': ' || pt.schemaname || '.' || pt.tablename ORDER BY 1)
                    FROM pg_catalog.pg_publication_tables pt)
)) AS inventario;


